// Function to add two large numbers represented as strings
string addLargeNumbers(string num1, string num2) {
    // Ensure num1 is the longer string
    if (num1.size() < num2.size()) swap(num1, num2);
    
    string result = "";
    int carry = 0;
    int n1 = num1.size(), n2 = num2.size();
    
    // Start adding from the end
    for (int i = 0; i < n1; i++) {
        int digit1 = num1[n1 - 1 - i] - '0'; // Convert char to int
        int digit2 = (i < n2) ? num2[n2 - 1 - i] - '0' : 0; // Convert char to int

        int sum = digit1 + digit2 + carry;
        carry = sum / 10;
        result += (sum % 10) + '0'; // Convert back to char
    }
    
    // If there's a carry left at the end
    if (carry) result += carry + '0';

    reverse(result.begin(), result.end()); // Reverse the result to get the correct order
    return result;
}

// Function to find the smallest integer that meets the criteria
void solve() {
    int n;
    cin >> n;

    // Prepare a vector to store the smallest integers
    vector<string> results(500, "-1");
    results[1] = "66"; // For n = 2, the smallest number is 66

    for (int i = 2; i < 500; i++) {
        // If we have 6's, we can start with 66
        // Build the number as a string of '3's and '6's
        string base = "6";
        for (int j = 1; j < i - 1; j++) {
            base += '3'; // Fill the rest with 3's
        }
        base += '6'; // End with a 6 to make it divisible by 66

        // If the number has to be exactly of length n, store it
        if (base.length() == i) {
            results[i] = base; // Store the result for this length
        }
    }

    cout << results[n] << endl; // Output the result for the input n
}

